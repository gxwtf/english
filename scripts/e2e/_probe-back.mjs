import { chromium } from 'playwright';
import pg from 'pg';
import dotenv from 'dotenv';
import { creds } from './lib.mjs';
dotenv.config({ path: '.env' });
const BASE = process.env.E2E_BASE || 'https://english.gxwtf.cn';
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const { identifier } = creds();
const u = await pool.query('SELECT "userId","userName",admin,email,"realName" FROM "User" WHERE "userName"=$1', [identifier]);
const user = u.rows[0];
const { sealData } = await import('iron-session');
const sealed = await sealData({ isLoggedIn: true, userId: user.userId, userName: user.userName, admin: user.admin }, { password: process.env.SECRET_COOKIE_PASSWORD, ttl: 7*24*3600 });
const q = await pool.query(`SELECT id FROM "QuestionQueue" WHERE "userId"=$1 AND "questionType"='word-card' AND status='GENERATED' ORDER BY "createdAt" DESC LIMIT 1`, [user.userId]);
const qid = q.rows[0].id;
const browser = await chromium.launch({ executablePath: '/usr/bin/microsoft-edge', args: ['--no-sandbox','--autoplay-policy=no-user-gesture-required','--mute-audio'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
const host = new URL(BASE).hostname;
if (host === 'english.gxwtf.cn') await ctx.addCookies([{ name: 'gxwtf_iron_auth', value: sealed, domain: host, path: '/', httpOnly: true, secure: true }]);
else await ctx.addCookies([{ name: 'gxwtf_iron_auth', value: sealed, url: BASE }]);
const page = await ctx.newPage();
page.on('response', r => { if (r.url().includes('/api/pronunciation')) console.log('  RESP', r.status(), r.url().slice(-60)); });
await page.goto(`${BASE}/practice/${qid}`, { waitUntil: 'domcontentloaded', timeout: 60000 });
const hint = page.getByText('点击翻转查看释义').first();
await hint.waitFor({ timeout: 60000 });
await page.waitForTimeout(1500);
// flip
await hint.click();
await page.waitForTimeout(1200);
const back = page.locator('div[style*="backface-visibility: hidden"][style*="rotateY(180deg)"]').first();
const group = back.locator('[data-pronunciation]').first();
console.log('back group text:', (await group.innerText()).replace(/\s+/g,' '));
const audio = group.locator('audio');
const before = await audio.evaluate(el => ({ src: el.currentSrc || el.src, paused: el.paused, t: el.currentTime, rs: el.readyState, err: el.error && el.error.code }));
console.log('audio before:', before);
await group.locator('[data-pronunciation-accent="us"]').click({ timeout: 5000 }).catch(e => console.log('CLICK FAIL', e.message.slice(0,120)));
await page.waitForTimeout(1800);
const after = await audio.evaluate(el => ({ src: el.currentSrc || el.src, paused: el.paused, t: el.currentTime, rs: el.readyState, err: el.error && el.error.code }));
console.log('audio after:', after);
const frontVisible = await page.getByText('点击翻转查看释义').first().isVisible().catch(()=>false);
console.log('front hint visible (flipped back?):', frontVisible);
await page.screenshot({ path: '/tmp/probe-back.png' });
await browser.close(); await pool.end();
